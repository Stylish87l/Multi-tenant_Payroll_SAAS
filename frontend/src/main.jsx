// src/main.jsx
import React from 'react';
import ReactDOM from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import { ApolloProvider } from '@apollo/client';
import App from './app';
import './index.css';

import { AuthProvider } from './context/AuthContext';
import client from './lib/apolloClient';

const REQUIRED_ENV = ['VITE_GRAPHQL_API_URL'];
const OPTIONAL_ENV = ['VITE_GRAPHQL_WS_URL'];

function ConfigError({ missing }) {
  return (
    <div style={{ height: '100vh', display: 'flex', alignItems: 'center', justifyContent: 'center', background: '#020617', color: '#94a3b8', fontFamily: 'Inter, system-ui, sans-serif', textAlign: 'center', padding: 20 }}>
      <div>
        <h1 style={{ color: '#fff', fontSize: '1.5rem', marginBottom: 10 }}>System configuration error</h1>
        <p style={{ marginBottom: 8 }}>The application is missing required environment configuration.</p>
        <div style={{ background: '#0f172a', padding: 12, borderRadius: 6, display: 'inline-block' }}>
          <strong style={{ color: '#fff' }}>Missing</strong>
          <div style={{ color: '#94a3b8', marginTop: 6 }}>{missing.join(', ')}</div>
        </div>
        <p style={{ marginTop: 12 }}>Please contact your administrator or check your deployment configuration.</p>
      </div>
    </div>
  );
}

function validateEnvironment() {
  const missingRequired = REQUIRED_ENV.filter((k) => !import.meta.env[k]);
  const missingOptional = OPTIONAL_ENV.filter((k) => !import.meta.env[k]);
  if (missingRequired.length) console.error(`Fatal: missing environment variables: ${missingRequired.join(', ')}`);
  else if (missingOptional.length) console.warn(`Optional env missing: ${missingOptional.join(', ')}`);
  return { ok: missingRequired.length === 0, missingRequired };
}

/**
 * Single service worker, generated by vite-plugin-pwa (registerType: 'prompt'). The hand-written
 * public/sw.js was removed: it pre-cached /src/main.jsx and /src/index.css (which don't exist in a
 * production build, so install ALWAYS failed) and fought the plugin's worker for the same /sw.js path.
 */
async function registerServiceWorker() {
  if (!import.meta.env.PROD || !('serviceWorker' in navigator)) return;
  try {
    const { registerSW } = await import('virtual:pwa-register');
    const updateSW = registerSW({
      onNeedRefresh() {
        window.dispatchEvent(new CustomEvent('sw:update', { detail: { apply: updateSW } }));
      },
    });
  } catch (err) {
    console.warn('PWA: service worker registration failed', err);
  }
}

(function bootstrap() {
  const rootEl = document.getElementById('root');
  if (!rootEl) throw new Error('Fatal: root element #root not found in index.html');

  const env = validateEnvironment();
  const root = ReactDOM.createRoot(rootEl);

  if (!env.ok) {
    root.render(<React.StrictMode><ConfigError missing={env.missingRequired} /></React.StrictMode>);
    return;
  }

  root.render(
    <React.StrictMode>
      <BrowserRouter>
        <ApolloProvider client={client}>
          <AuthProvider>
            <App />
          </AuthProvider>
        </ApolloProvider>
      </BrowserRouter>
    </React.StrictMode>
  );

  registerServiceWorker();
})();
